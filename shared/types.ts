export type Lang = "en" | "ko" | "ja" | "zh-CN" | "zh-TW";
export type Localized = Record<Lang, string>;
export type Point = { lat: number; lng: number };
export type Area = {
  id: string;
  cityId: string;
  name: Localized;
  point: Point;
  districtId: string;
  aliases: Localized;
};
export type Place = {
  id: string;
  areaId: string;
  name: Localized;
  description: Localized;
  address: string;
  point: Point;
  category: string;
  tags: string[];
  costMin: number;
  costMax: number;
  stay: number;
  wait: number;
  hours: { day: number; open: number; close: number; lastEntry: number }[];
  reservation: boolean;
  sample: boolean;
  source: string;
  checkedAt: string | null;
  children: boolean | null;
  accessible: boolean | null;
  diet: string[];
  stamp: boolean;
  couponId?: string;
  art: string;
  published: boolean;
};
export type Conditions = {
  areaId: string;
  origin: Point;
  minutes: number;
  budget: number;
  interests: string[];
  transport: "walk" | "transit" | "car";
  companion: string;
  startAt: string;
  returnPoint: Point | null;
  deadline: string | null;
  children: boolean;
  accessible: boolean;
  diet: string;
  tripStart: string;
  tripEnd: string;
};
export type Stop = {
  placeId: string;
  travel: number;
  arrival: string;
  departure: string;
  stay: number;
  wait: number;
  costMin: number;
  costMax: number;
};
export type Route = {
  id: string;
  stops: Stop[];
  minutes: number;
  costMin: number;
  costMax: number;
  transportCost: number;
  returnMinutes: number;
  buffer: number;
  startAt: string;
  endAt: string;
  estimated: true;
  sample: boolean;
  conditions: Conditions;
};
