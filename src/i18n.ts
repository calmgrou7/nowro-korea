export function t(key: string, lang: Lang) {
  return (
    copy[key]?.[languages.indexOf(lang)] ||
    copy[key]?.[0] ||
    "Information unavailable"
  );
}
export function initialLanguage(): Lang {
  try {
    const stored = localStorage.getItem("nowro-language");
    if (languages.includes(stored as Lang)) return stored as Lang;
  } catch {}
  // English-first launch for international and domestic travelers.
  // Always preserve an explicitly selected language on later visits.
  return "en";
}
